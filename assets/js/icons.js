// The keyword that appears first wins: "Snacks for the train" is food, "Toto to the hotel" is a ride.
export function iconFor(title) {
  const t = String(title || '').toLowerCase();
  let best = 'receipt';
  let at = Infinity;
  for (const [name, re] of KINDS) {
    const m = re.exec(t);
    if (m && m.index < at) {
      at = m.index;
      best = name;
    }
  }
  return best;
}
